/// <reference path="./types/express.d.ts" />
import express, { Request, Response } from "express";
import { appRouter, createContext } from "./trpc";
import * as trpcExpress from "@trpc/server/adapters/express";
import { upload, getSafeFilePath } from "./utils/multer";
import { db } from "./lib/db";
import path from "path";
import "dotenv/config";
import cors from "cors";
import multer from "multer";
import { validateEnv, getConfig } from "./config/env";
import { logger } from "./utils/logger";
import { authenticate, User } from "./lib/auth";
import { Folder, getFolderFromRequest, } from "./lib/folder";
import { canAccess, File } from "./lib/file";
import { errorHandler } from "./lib/errors";


// Database is now imported from lib/db.ts
// Validate environment variables before starting server
validateEnv();

const config = getConfig();

const app = express();

app.use(
  cors({
    origin: config.CORS_ORIGIN,
    credentials: true,
  })
);

// Parse cookies
app.use(require('cookie-parser')());

app.use("/express", express.json());
app.use(
  "/trpc",
  trpcExpress.createExpressMiddleware({
    router: appRouter,
    createContext,
    onError({ path, error }) {
      logger.error(`trPC Failed on ${path ?? " "}: ${error.message}`);
    },
  })
);

app.post("/files", authenticate, (req, res, next) => {
  upload.array("files")(req, res, (err) => {
    if (err instanceof multer.MulterError) {
      if (err.code === 'LIMIT_FILE_SIZE') {
        return res.status(400).json({ error: 'File too large. Maximum size is 10MB.' });
      }
      if (err.code === 'LIMIT_FILE_COUNT') {
        return res.status(400).json({ error: 'Too many files. Maximum 10 files per upload.' });
      }
      return res.status(400).json({ error: err.message });
    }
    if (err) {
      return res.status(400).json({ error: err.message });
    }
    next();
  });
}, async (req, res) => {
  try {
    const folder = getFolderFromRequest(req, res);
    if (!folder) {
      return res.status(400).json({ error: 'Invalid folder' });
    }

    const files = req.files as Express.Multer.File[];
    const user = req.user;

    if (!files || files.length === 0) {
      return res.status(400).json({ error: 'No files uploaded' });
    }

    const response = [];

    for (const file of files) {
      const newFile: File = {
        type: 'file',
        name: file.originalname,
        id: file.filename, // Use the unique filename generated by multer
        size: file.size,
        owner: user!.id,
        folder: folder.id,
        permissions: {},
        lastModified: Date.now(),
      };

      db.data.files.push(newFile);
      response.push({
        id: newFile.id,
        name: newFile.name,
        size: newFile.size,
        lastModified: newFile.lastModified
      }); // Don't expose internal data
    }

    await db.write();
    res.status(201).json(response);
  } catch (error) {
    console.error('File upload error:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

app.get("/files/:folder/:file", authenticate, async (req, res) => {
  try {
    const fileId = req.params["file"];
    const folderId = req.params["folder"];
    const user = req.user!;

    // Input validation
    if (!fileId || !folderId) {
      return res.status(400).json({ error: 'File ID and folder ID are required' });
    }

    const file = db.data.files.find(
      (f: File) => f.folder === folderId && f.id === fileId
    );

    if (!file) {
      return res.status(404).json({ error: 'File not found' });
    }

    if (!canAccess(file, user.id)) {
      return res.status(403).json({ error: "You don't have access to this file" });
    }

    const safeFilePath = getSafeFilePath(file.id);
    
    // Check if file exists on disk
    if (!require('fs').existsSync(safeFilePath)) {
      return res.status(404).json({ error: 'File not found on disk' });
    }

    // Set proper headers
    const sanitizedFilename = file.name.replace(/[^a-zA-Z0-9._-]/g, '_');
    res.set({
      'Content-Disposition': `attachment; filename="${sanitizedFilename}"`,
      'Content-Type': 'application/octet-stream',
      'X-Content-Type-Options': 'nosniff'
    });

    res.sendFile(path.resolve(safeFilePath));
  } catch (error) {
    console.error('File download error:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

// Global error handler - must be last middleware
app.use(errorHandler);

const startServer = async () => {
  try {
    // Initialize database
    await db.init();
    console.log('✅ Database initialized successfully');
    
    app.listen(config.PORT, () => {
      console.log(`🚀 Server is running on http://localhost:${config.PORT}`);
      console.log(`Environment: ${config.NODE_ENV}`);
      console.log(`CORS Origin: ${config.CORS_ORIGIN}`);
      console.log(`Database: ${config.DATABASE_FILE}`);
    });
  } catch (error) {
    console.error('Failed to start server:', error);
    process.exit(1);
  }
};

startServer();
